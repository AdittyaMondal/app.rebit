    <h3>What is not allowed</h3>

    <ul>
        <li><strong>Hate.</strong> Slurs, racist or sexist stereotypes, dehumanisation, incitement of fear or discrimination, and hateful references, symbols or logos.</li>
        <li><strong>Abuse and harassment.</strong> Insults, unwanted sexual or graphic content, denial of violent events, targeted harassment, and inciting others to harass.</li>
        <li><strong>Violence and dangerous content.</strong> Threats, glorification of violence, and content that encourages dangerous acts.</li>
        <li><strong>Child safety.</strong> Any sexualisation of minors, or content that puts a child at risk. This is removed immediately and reported to the relevant authorities.</li>
        <li><strong>Privacy and safety.</strong> Sharing someone's private information, images or location without their consent.</li>
        <li><strong>Spam.</strong> Repetitive or deceptive posting, engagement farming, and misleading links.</li>
        <li><strong>Suicide or self-harm.</strong> Encouraging or instructing self-harm. If you are struggling, please contact local support services.</li>
        <li><strong>Sensitive or disturbing media.</strong> Gratuitously graphic imagery.</li>
        <li><strong>Impersonation.</strong> Pretending to be another person, business or organisation in a way designed to deceive.</li>
        <li><strong>Violent and hateful entities.</strong> Content promoting organisations that use or advocate violence to further their cause.</li>
    </ul>

    <h3>Reporting and blocking</h3>

    <p>
